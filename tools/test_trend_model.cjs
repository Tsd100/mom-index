const assert = require('node:assert/strict');
const {buildTrend} = require('../src/mom_index/frontend/trend-model.js');
const point=(date,index=40,definition='v1')=>({date,index,definition_id:definition,quality:{status:'ok',valid_count:35},details:{mom_buy_index:22,mom_sell_index:11}});
const data={sector_history:{gold:[point('2026-11-01'),point('2026-11-03',55)]},price_history:{gold:[{date:'2026-11-02',price:9}]}};
const options={sector:'gold',range:'custom',start:'2026-11-01',end:'2026-11-03',metric:'index'};
let view=buildTrend(data,options,'2026-11-08');
assert.deepEqual(view.dates,['2026-11-01','2026-11-02','2026-11-03']);
assert.deepEqual(view.values,[40,null,55]);
assert.deepEqual(view.samples,[35,null,35]);
assert.equal(view.comparison,null,'缺采集日不能计算跨缺口变化');
data.sector_history.gold.splice(1,0,point('2026-11-02',45));
view=buildTrend(data,options,'2026-11-08');
assert.equal(view.comparison.delta,15);
assert.equal(view.comparison.from,'2026-11-01');
data.sector_history.gold[1].definition_id='old';
assert.equal(buildTrend(data,options,'2026-11-08').comparison,null);
data.sector_history.gold[1].quality.status='stale';
assert.equal(buildTrend(data,options,'2026-11-08').values[1],null);
assert.equal(buildTrend(data,{...options,metric:'buy'},'2026-11-08').values[0],22);
assert.equal(buildTrend(data,{...options,metric:'sell'},'2026-11-08').values[0],11);
assert.equal(buildTrend(data,{...options,range:'90'},'2026-11-08').dates.length,90);
assert(buildTrend(data,{...options,start:'2026-11-04'},'2026-11-08').error);
assert(buildTrend(data,{...options,start:'2026-02-30'},'2026-11-08').error);
assert(buildTrend(data,{...options,end:'2026-11-09'},'2026-11-08').error);
assert.equal(buildTrend({}, {sector:'gold',range:'7',metric:'index'},'2026-11-08').dates.length,7);
assert.equal(buildTrend(data,{...options,range:'all'},'2026-11-08').dates[0],'2026-11-01');
console.log('PASS: trend ranges, gaps, quality, definitions, metrics and empty history');
